/**
 * Вивантаження в таблицю.
 *
 * Помилка тут не падає, а зсуває колонки: один запис із крапкою з комою
 * у назві — і в переліку, який поїхав у штаб, номери належать не тим
 * речам. Помітити це в файлі на двісті рядків нема як.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { csvCell, csvRow, toCsv, csvName, latin, BOM } from '../lib/csv.js';

/* ── клітинка ──────────────────────────────────────────────────────────── */

test('звичайне значення йде як є', () => {
  assert.equal(csvCell('Кропива'), 'Кропива');
  assert.equal(csvCell(42), '42');
});

test('порожнє лишається порожнім', () => {
  assert.equal(csvCell(''), '');
  assert.equal(csvCell(null), '');
  assert.equal(csvCell(undefined), '');
});

test('крапка з комою всередині береться в лапки — інакше зсуне колонки', () => {
  assert.equal(csvCell('рація; кабель'), '"рація; кабель"');
});

test('лапки подвоюються', () => {
  assert.equal(csvCell('модель "Альфа"'), '"модель ""Альфа"""');
});

test('перенос рядка не розриває запис', () => {
  assert.equal(csvCell('перший\nдругий'), '"перший\nдругий"');
  assert.equal(csvCell('перший\r\nдругий'), '"перший\r\nдругий"');
});

test('пробіли по краях зберігаються — у номерах вони інколи значущі', () => {
  assert.equal(csvCell(' 001 '), '" 001 "');
});

/* ── рядок ─────────────────────────────────────────────────────────────── */

test('клітинки зʼєднуються крапкою з комою', () => {
  assert.equal(csvRow(['1', 'Кропива', 'A-100']), '1;Кропива;A-100');
});

test('порожні клітинки лишають своє місце', () => {
  assert.equal(csvRow(['1', '', 'A-100']), '1;;A-100');
});

/* ── увесь лист ────────────────────────────────────────────────────────── */

const HEADERS = ['№', 'Назва', 'Модель', 'S/N', 'Статус'];
const ROWS = [
  ['1', 'Кропива', 'КРП-2', 'SN-001', 'Видано'],
  ['2', 'Кропива', 'КРП-3', 'SN-002', 'Склад'],
];

test('заголовок стоїть першим рядком', () => {
  const out = toCsv(HEADERS, ROWS);
  assert.equal(out.split('\r\n')[0], '№;Назва;Модель;S/N;Статус');
});

test('усі записи на місці й у своєму порядку', () => {
  const lines = toCsv(HEADERS, ROWS).split('\r\n');
  assert.equal(lines.length, 3);
  assert.equal(lines[1], '1;Кропива;КРП-2;SN-001;Видано');
  assert.equal(lines[2], '2;Кропива;КРП-3;SN-002;Склад');
});

test('короткий рядок добивається порожніми — у таблиці хвіст не зберігається', () => {
  const out = toCsv(HEADERS, [['3', 'Кропива']]);
  assert.equal(out.split('\r\n')[1], '3;Кропива;;;');
});

test('порожній лист — сам лише заголовок', () => {
  assert.equal(toCsv(HEADERS, []), '№;Назва;Модель;S/N;Статус');
  assert.equal(toCsv(HEADERS), '№;Назва;Модель;S/N;Статус');
});

test('колонки з паролями у файл не потрапляють', () => {
  // перелік майна ходить по руках і лягає в пошту; пароль від рації в
  // такому файлі — це не вивантаження, а роздача
  const h = ['№', 'Назва', 'Пароль', 'Статус'];
  const r = [['1', 'Рація', 'секрет', 'Видано']];
  const out = toCsv(h, r, { skip: [2] });
  assert.equal(out.split('\r\n')[0], '№;Назва;Статус');
  assert.equal(out.split('\r\n')[1], '1;Рація;Видано');
  assert.ok(!out.includes('секрет'));
  assert.ok(!out.includes('Пароль'));
});

test('викидання кількох колонок не плутає порядок решти', () => {
  const out = toCsv(HEADERS, ROWS, { skip: [0, 3] });
  assert.equal(out.split('\r\n')[0], 'Назва;Модель;Статус');
  assert.equal(out.split('\r\n')[1], 'Кропива;КРП-2;Видано');
});

test('запис із крапкою з комою не ламає розкладку', () => {
  const out = toCsv(['Назва', 'Модель'], [['рація; кабель', 'КРП-2']]);
  assert.equal(out.split('\r\n')[1], '"рація; кабель";КРП-2');
});

/* ── імʼя файла ────────────────────────────────────────────────────────── */

test('у назві файла видно лист і день', () => {
  assert.equal(csvName('Кропива', '09.09.2026'), 'Kropyva 09.09.2026.csv');
});

test('назва листа з пробілами лишається читабельною', () => {
  assert.equal(csvName('майно не облік', '09.09.2026'), 'maino ne oblik 09.09.2026.csv');
});

test('символи, заборонені в іменах файлів, прибираються', () => {
  assert.equal(csvName('Майно/рота: 1', '09.09.2026'), 'Maino rota 1 09.09.2026.csv');
});

/* ── транслітерація ────────────────────────────────────────────────────── */

test('кирилиця стає латиницею — інакше браузер губить ім\'я файла', () => {
  // перевірено в Chromium: «Кропива 09.09.2026.csv» зберігається як
  // «download», без розширення, і таблиця такий файл не відкриває
  assert.equal(latin('Кропива'), 'Kropyva');
  assert.equal(latin('ПНВ'), 'PNV');
  assert.equal(latin('Тепловізори'), 'Teplovizory');
  assert.equal(latin('Радейки'), 'Radeiky');
});

test('латиниця й цифри лишаються як були', () => {
  assert.equal(latin('Kropyva 2'), 'Kropyva 2');
});

test('великі літери лишаються великими', () => {
  assert.equal(latin('Щит'), 'Shchyt');
  assert.equal(latin('Її'), 'Ii');
});

test('у результаті лише те, що переживе будь-яку файлову систему', () => {
  assert.match(latin('Майно/рота: №1'), /^[A-Za-z0-9 ]+$/);
});

test('назва з самих символів не дає порожнього імені', () => {
  assert.equal(latin('///'), 'export');
  assert.equal(latin(''), 'export');
  assert.equal(latin(null), 'export');
});

/* ── позначка кодування ────────────────────────────────────────────────── */

