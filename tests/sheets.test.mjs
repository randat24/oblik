/**
 * `fromSerial` — найтихіша функція застосунку.
 *
 * Google Таблиці віддають дату не рядком, а числом: 46254 замість
 * «20.08.2026». Через неї проходять усі дати всіх розділів — склад, ящики,
 * звірки, акти, доставки. Коли вона помиляється, ніщо не падає: у картці
 * просто зʼявляється «46254» або чужий день, і людина вирішує, що
 * застосунок бреше.
 *
 * Українська локаль таблиці додає своє: дроби через кому, а тисячі —
 * через пробіл, іноді нерозривний.
 */
import test from 'node:test';
import assert from 'node:assert/strict';

import { fromSerial, todayStr } from '../lib/sheets.js';

/* ── дати ──────────────────────────────────────────────────────────────── */

test('число таблиці стає датою: відлік від 30.12.1899', () => {
  assert.equal(fromSerial(46254), '20.08.2026');
});

test('перший день відліку', () => {
  assert.equal(fromSerial(1), '31.12.1899');
});

test('день і місяць доповнюються нулем', () => {
  assert.equal(fromSerial(45658), '01.01.2025');
});

test('дробова частина — це час; на дату вона не впливає', () => {
  assert.equal(fromSerial(46254.75), '20.08.2026');
});

test('кома як десятковий роздільник — саме так віддає українська локаль', () => {
  assert.equal(fromSerial('46254,75'), '20.08.2026');
});

test('пробіл і нерозривний пробіл між тисячами не заважають', () => {
  assert.equal(fromSerial('46 254'), '20.08.2026');
  assert.equal(fromSerial('46 254'), '20.08.2026');
});

/* ── що не є числом таблиці ────────────────────────────────────────────── */

test('уже готова дата лишається як є', () => {
  assert.equal(fromSerial('20.08.2026'), '20.08.2026');
});

test('порожнє лишається порожнім', () => {
  assert.equal(fromSerial(''), '');
  assert.equal(fromSerial(null), '');
  assert.equal(fromSerial(undefined), '');
});

test('текст не перетворюється на дату', () => {
  assert.equal(fromSerial('невідомо'), 'невідомо');
});

test('число поза межами відліку лишається числом', () => {
  // 0 і мільйон — це не дати, а чиясь помилка при заповненні; підміняти
  // її правдоподібним днем гірше, ніж лишити видимою
  assert.equal(fromSerial(0), '0');
  assert.equal(fromSerial(1000000), '1000000');
});

/* ── час ───────────────────────────────────────────────────────────────── */

test('час береться з дробової частини доби', () => {
  assert.equal(fromSerial(0.5, 'time'), '12:00');
  assert.equal(fromSerial(0.25, 'time'), '06:00');
  assert.equal(fromSerial(0, 'time'), '00:00');
});

test('час рахується і від повного числа з датою', () => {
  assert.equal(fromSerial(46254.5, 'time'), '12:00');
});

test('час із комою — знову українська локаль', () => {
  assert.equal(fromSerial('0,6979166667', 'time'), '16:45');
});

test('готовий час лишається як є', () => {
  assert.equal(fromSerial('16:45', 'time'), '16:45');
});

/* ── сьогодні ──────────────────────────────────────────────────────────── */

test('todayStr пише день у тому ж вигляді, що й таблиця', () => {
  assert.match(todayStr(), /^\d{2}\.\d{2}\.\d{4}$/);
});
