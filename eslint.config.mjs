import js from '@eslint/js';
import globals from 'globals';
import reactHooks from 'eslint-plugin-react-hooks';

/*
 * Лінтер тут стоїть не для краси й не для смаків про лапки.
 *
 * У вересні збереження прогресу — множення, абетка, уроки — тижнями
 * падало з «readSheet is not defined»: у lib/health.js лишився виклик
 * функції, якої в модулі немає. Ні тести, ні складання такого не бачать.
 * Тести не заходять у savePatch без живих ключів до таблиці, а збірці
 * байдуже: синтаксис цілий, імпорти цілі, а ReferenceError трапляється
 * лише в мить виклику — тобто рівно тоді, коли людина тисне «Зберегти».
 *
 * `no-undef` знаходить це за секунду й безкоштовно. Решта правил — того
 * самого роду: те, що майже напевно помилка, а не смак. Форматування,
 * лапки, крапки з комою лінтер не чіпає: сперечатися з ним про кому —
 * це витрачати увагу там, де вона нічого не рятує.
 */

export default [
  js.configs.recommended,

  {
    files: ['**/*.js', '**/*.mjs'],
    plugins: { 'react-hooks': reactHooks },
    languageOptions: {
      ecmaVersion: 2024,
      sourceType: 'module',
      globals: {
        ...globals.browser,
        ...globals.node,
      },
      parserOptions: {
        // у сторінках і компонентах — JSX
        ecmaFeatures: { jsx: true },
      },
    },
    rules: {
      /*
       * Головне правило. Саме воно ловить виклик імені, якого немає.
       */
      'no-undef': 'error',

      /*
       * Невикористане — попередження, а не помилка. Забутий імпорт чи
       * змінна не ламають нічого сьогодні, але показують місце, де код
       * міняли поспіхом. Аргументи функцій не чіпаємо: у зворотних
       * викликах порядок важливіший за використання.
       */
      'no-unused-vars': ['warn', { args: 'none', varsIgnorePattern: '^_' }],

      // порожній `catch {}` — свідомий прийом у цьому коді: збій читання
      // кешу чи localStorage не має валити сторінку
      'no-empty': ['error', { allowEmptyCatch: true }],

      /*
       * Нерозривний пробіл посеред коду — справжня біда: очима не
       * відрізнити, а редактор не знаходить рядок пошуком. Але в
       * регулярних виразах він стоїть навмисно: українська локаль
       * таблиці розділяє ним тисячі, і саме його ми звідти й вичищаємо.
       */
      'no-irregular-whitespace': ['error', { skipRegExps: true }],

      /*
       * `let data = {}` перед `try { data = JSON.parse(...) }` формально
       * зайве — значення завжди перезаписують. Але воно там свідомо:
       * видно, що буде, якщо розбір впаде. Це привід подивитись, а не
       * привід зупинити збірку.
       */
      'no-useless-assignment': 'warn',

      /*
       * Правила гачків. Перше — про порядок виклику, і це справжня
       * помилка: гачок під `if` ламає React мовчки й не щоразу.
       *
       * Друге лише попереджає. У коді вже стоять рядки
       * `// eslint-disable-line react-hooks/exhaustive-deps` — отже,
       * колись його вмикали, а потім лінтер із проєкту зник, і
       * відключення лишились висіти. Тепер вони знову означають те,
       * що написано.
       */
      'react-hooks/rules-of-hooks': 'error',
      'react-hooks/exhaustive-deps': 'warn',
    },
  },

  {
    /*
     * Збірку React для пісочниці робить `scripts/build-sandbox.mjs` — це
     * стиснений чужий код, який ніхто не читає й не править руками.
     * Лінтувати його означає щоразу отримувати сотню зауважень до того,
     * чого ми не писали.
     */
    ignores: ['.next/**', 'node_modules/**', 'public/vendor/**'],
  },
];
