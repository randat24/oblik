/** Питання одного уроку */
export const forLesson = (id) => QUESTIONS.filter((q) => q.lesson === id);

/** Уроки, для яких питання вже написані */
export const COVERED = [...new Set(QUESTIONS.map((q) => q.lesson))];

/**
 * Питання, яке цього разу дістанеться уроку.
 *
 * Вибирається за рівнем, а не навмання: так із кожним поверненням
 * приходить інше, а повторний показ того самого стає можливим лише
 * після того, як усі інші вже були.
 */
export function pick(id, level = 0) {
  const qs = forLesson(id);
  if (!qs.length) return null;
  return qs[Math.max(0, level | 0) % qs.length];
}

/**
 * Уроки, які час повторити.
 *
 * Тільки пройдені й тільки ті, для яких є питання: решта в чергу не
 * потрапляє й мовчки чекає, доки питання напишуть.
 */
export function dueLessons(prog, todayStamp = Date.now()) {
  const out = [];
  COVERED.forEach((id) => {
    const p = (prog || {})[id];
    if (!p || p.state !== 'done') return;
    const level = Math.max(0, p.level | 0);
    const seen = stampOf(p.asked);
    // ще жодного разу не питали — чекати нема чого
    const days = seen ? Math.floor((todayStamp - seen) / DAY) : Infinity;
    if (days >= dueIn(level)) out.push({ id, level, days, question: pick(id, level) });
  });
  // найзабутіше першим: те, що чекає довше, і забулось глибше
  return out.sort((a, b) => b.days - a.days || a.level - b.level);
}

/**
 * Черга на сьогодні.
 *
 * Пʼять питань — це хвилини три. Більше не влазить у «зайшов між
 * справами», а саме так повторення й роблять: не сідають за нього
 * окремо, а відкривають між іншим.
 */
export const DAY_SIZE = 5;

export const buildQueue = (prog, todayStamp = Date.now(), size = DAY_SIZE) =>
  dueLessons(prog, todayStamp).slice(0, Math.max(0, size));

/** Скільки всього чекає — щоб показати число, не будуючи чергу */
export const dueCount = (prog, todayStamp = Date.now()) => dueLessons(prog, todayStamp).length;

/**
 * Підсумок для картки розділу: скільки понять тримається, скільки
 * чекають і скільки ще жодного разу не поверталось.
 */
export function recallStats(prog, todayStamp = Date.now()) {
  let held = 0;
  let learning = 0;
  let fresh = 0;
  COVERED.forEach((id) => {
    const p = (prog || {})[id];
    if (!p || p.state !== 'done') return;
    if (!stampOf(p.asked)) fresh += 1;
    else if ((p.level | 0) >= MAX_LEVEL) held += 1;
    else learning += 1;
  });
  return { held, learning, fresh, total: held + learning + fresh, due: dueCount(prog, todayStamp) };
}
