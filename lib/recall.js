/**
 * Повторення пройденого.
 *
 * Курс проходять один раз: урок зроблено — і більше він не повертається
 * ніколи. Для шістдесяти чотирьох уроків це означає рівно те, що й
 * звучить: людина доходить до кінця й памʼятає останні десять. «Умову»
 * робили на третій день, React відкривають на сороковий — і `if` за цей
 * час вивітрився разом з усім, що на ньому стоїть.
 *
 * Тренажер множення таку машину має давно: рівень на кожен приклад,
 * повернення за розкладом, окремо важкі. Тут — те саме для понять.
 *
 * Проміжки свої, а не ті, що в множенні. Там вони навмисно щільні —
 * таблиця має відповідатись не думаючи, тож максимум тиждень. Поняттю
 * «замикання» відповідати на швидкість не треба: його досить упізнавати,
 * і місяць між показами для цього достатньо.
 *
 * Питання перевіряють не памʼять на слова, а те місце, де новачок
 * помиляється. «Що таке тернарний оператор» перевіряє переказ; «що
 * надрукує цей код» перевіряє розуміння — і саме друге вивітрюється.
 */

/** Через скільки днів повернути поняття */
export const LADDER = [0, 1, 3, 7, 14, 30];
export const MAX_LEVEL = LADDER.length - 1;

export const dueIn = (level) => LADDER[Math.min(Math.max(level | 0, 0), MAX_LEVEL)];

/**
 * Рівень після відповіді.
 *
 * Помилка відкидає на щабель, а не в нуль: хто пʼять разів згадав і раз
 * забув, не починає спочатку. Але й не лишається на місці — забув, отже
 * рано розтягувати проміжок.
 */
export function nextLevel(level, right) {
  const n = Math.max(0, level | 0);
  return right ? Math.min(MAX_LEVEL, n + 1) : Math.max(0, n - 1);
}

/** «13.09.2026» → число для порівнянь; сміття дає 0, а не падіння */
export function stampOf(d) {
  const m = /^(\d{2})\.(\d{2})\.(\d{4})$/.exec(String(d || '').trim());
  return m ? Date.UTC(+m[3], +m[2] - 1, +m[1]) : 0;
}

