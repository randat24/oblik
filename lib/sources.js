/** Джерело, якому належить адреса; чуже посилання дає `null` */
export function sourceOf(url) {
  const u = String(url || '').toLowerCase();
  return SOURCES.find((s) => u.includes(s.host)) || null;
}

/** Скільки джерел справді відкривали з цього застосунку */
export function sourceStats() {
  return {
    total: SOURCES.length,
    checked: SOURCES.filter((s) => s.state === 'ok').length,
    blocked: SOURCES.filter((s) => s.state === 'blocked').length,
  };
}

