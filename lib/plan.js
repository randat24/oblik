/** Урок у цьому застосунку, що відповідає кроку плану */
export const lessonOf = (step) => CODE_LESSONS.find((l) => l.id === step.lesson) || null;

/*
 * Розбір власного коду, якщо на цю тему він уже є.
 *
 * Розбори з'явились раніше за цей план і роблять те саме, тільки
 * докладніше: ведуть по справжньому файлу рядок за рядком. Писати поруч
 * другу інструкцію про той самий файл — це роздвоювати те, що має бути
 * одним; тому план не переказує розбір, а відсилає до нього.
 */
export const tourOf = (step) => TOURS.find((x) => x.id === step.tour) || null;

/**
 * Наступні кроки: перші кілька, яких ще не пройдено.
 *
 * Показувати всі чотирнадцять одразу — це показати дорогу завдовжки в
 * пів року й нічого більше. Видно має бути те, чим зайнятись сьогодні.
 */
export function nextSteps(done = {}, chunk = CHUNK) {
  const left = PLAN.filter((s) => !done[s.lesson] || done[s.lesson].state !== 'done');
  return left.slice(0, chunk);
}

/** Скільки пройдено — за станом уроків, бо окремих позначок план не веде */
export function planProgress(done = {}) {
  const ready = PLAN.filter((s) => done[s.lesson]?.state === 'done').length;
  return { ready, total: PLAN.length };
}
