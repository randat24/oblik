/** Пошук по назві, питанню й коду — щоб знаходилось і «flex», і «по центру» */
export function findCards(q) {
  const t = String(q || '').trim().toLowerCase();
  if (!t) return REF_CARDS;
  return REF_CARDS.filter((c) =>
    [c.t, c.q, c.code, c.note, c.here].join(' ').toLowerCase().includes(t));
}
