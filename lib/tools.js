export function toolStats(prog) {
  // `?? {}` замість значення за замовчуванням: сюди приходить `data.code`,
  // а він буває саме `null`, і тоді замовчування не вмикається
  const p = prog ?? {};
  const done = TOOL_LESSONS.filter((l) => p[l.id]?.state === 'done').length;
  return { done, total: TOOL_LESSONS.length };
}

