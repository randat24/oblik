/**
 * Інструменти: термінал, Git, оточення, пошук причини.
 *
 * Курс учить писати код у пісочниці просто на сторінці — і це правильно
 * для початку: не треба нічого ставити, нічого налаштовувати, помилився
 * — перезавантажив. Але справжня робота починається не там. Вона
 * починається з чорного вікна, у якому треба щось надрукувати, і з
 * питання «а як тепер повернути, як було».
 *
 * Ці уроки живуть окремо від курсу, а не всередині нього, і це не
 * недогляд:
 *
 *   Терміналом не «оволодівають на дванадцятому рівні». Він потрібен
 *   тоді, коли потрібен, — і тоді ж його й читають. Поставити його
 *   уроком номер один означає загородити вхід новачкові, який хотів
 *   побачити на екрані свій перший заголовок. Поставити шістдесят сьомим
 *   означає, що людина рік працює без Git.
 *
 * Тому вони відкриті завжди й не зсувають черги курсу. Порядок
 * усередині все ж є — Git після терміналу, бо інакше нема де набирати
 * команди, — але це порада, а не замок.
 *
 * Перевірити їх запуском коду не можна: те, що тут відбувається,
 * відбувається на чужому комп'ютері. Тому кожен урок — це кроки, які
 * робиш у себе, і кілька питань, на які неможливо відповісти, не
 * зробивши. «Що надрукував `pwd` — шлях чи перелік файлів» перевіряє не
 * пам'ять, а те, що людина справді дивилась на екран.
 */

