/**
 * Вивантаження листа у файл, який відкриває будь-яка таблиця.
 *
 * Потрібне не для того, щоб дані кудись переїхали — вони й так у Google
 * Таблиці. Потрібне тоді, коли перелік треба комусь віддати: у штаб, у
 * сусідній підрозділ, у папери. Такий перелік має відкритися в Excel на
 * чужому ноутбуці з першого разу, без питань про кодування.
 *
 * Звідси три рішення, які виглядають дрібними, а насправді і є всією
 * складністю CSV:
 *
 *   роздільник ;   українська й російська локалі Excel чекають саме
 *                  крапку з комою; з комою він складе весь рядок в одну
 *                  клітинку. Google Таблиці визначають роздільник самі,
 *                  тож крапка з комою безпечна для обох.
 *
 *   BOM на початку Excel без нього читає UTF-8 як однобайтове кодування,
 *                  і замість «Кропива» виходить «ÐšÑ€Ð¾Ð¿Ð¸Ð²Ð°».
 *
 *   лапки          у назвах трапляються і крапка з комою, і лапки, і
 *                  переноси рядків. Без екранування один такий запис
 *                  зсуває всі колонки нижче.
 */

const SEP = ';';

/** Excel читає UTF-8 лише коли файл починається з цієї позначки */
export const BOM = '﻿';

/**
 * Одна клітинка.
 *
 * У лапки беремо не лише те, що містить роздільник: пробіли по краях
 * таблиці зазвичай зʼїдають, а в позивних і номерах вони інколи значущі.
 */
export function csvCell(value) {
  const s = value === null || value === undefined ? '' : String(value);
  if (!s) return '';
  if (/["\n\r;]/.test(s) || s !== s.trim()) return '"' + s.replace(/"/g, '""') + '"';
  return s;
}

/** Рядок клітинок */
export const csvRow = (cells) => cells.map(csvCell).join(SEP);

/**
 * Лист у текст CSV.
 *
 * `skip` — номери колонок, яких у файлі бути не має. Через нього
 * викидаються паролі: перелік майна ходить по руках і лягає в пошту, і
 * пароль від рації в такому файлі — це не вивантаження, а роздача.
 */
export function toCsv(headers, rows, { skip = [] } = {}) {
  const drop = new Set(skip);
  const keep = (headers || []).map((_, i) => i).filter((i) => !drop.has(i));
  // рядок може бути коротшим за заголовок — у таблиці хвіст порожніх
  // клітинок просто не зберігається
  const take = (r) => keep.map((i) => (r || [])[i]);
  return [csvRow(take(headers)), ...(rows || []).map((r) => csvRow(take(r)))].join('\r\n');
}

/*
 * Назва листа латиницею.
 *
 * Не косметика: браузер відмовляється від імені файла з кирилицею й
 * зберігає його як «download» — без розширення, тож таблиця такий файл
 * не відкриває взагалі. Перевірено в Chromium: те саме ім'я латиницею
 * доходить цілим, кирилицею — зникає.
 *
 * Тому ім'я транслітеруємо, а не лишаємо як є: «Kropyva» в теці
 * завантажень читається, «download» — ні.
 */
const LATIN = {
  а: 'a', б: 'b', в: 'v', г: 'h', ґ: 'g', д: 'd', е: 'e', є: 'ie', ж: 'zh',
  з: 'z', и: 'y', і: 'i', ї: 'i', й: 'i', к: 'k', л: 'l', м: 'm', н: 'n',
  о: 'o', п: 'p', р: 'r', с: 's', т: 't', у: 'u', ф: 'f', х: 'kh', ц: 'ts',
  ч: 'ch', ш: 'sh', щ: 'shch', ь: '', ю: 'iu', я: 'ia',
  // трапляються й російські літери — лист заводили руками
  ы: 'y', э: 'e', ъ: '', ё: 'e',
};

export function latin(s) {
  const out = String(s || '')
    .split('')
    .map((ch) => {
      const low = ch.toLowerCase();
      if (low in LATIN) {
        const t = LATIN[low];
        return ch === low ? t : t.charAt(0).toUpperCase() + t.slice(1);
      }
      return /[A-Za-z0-9]/.test(ch) ? ch : ' ';
    })
    .join('')
    .replace(/\s+/g, ' ')
    .trim();
  return out || 'export';
}

/** «Kropyva 09.09.2026.csv» — щоб у теці завантажень було видно, що це */
export function csvName(sheet, date) {
  return `${latin(sheet)} ${date}.csv`;
}
