/**
 * Числа з годинника: одиниці й межі здорового глузду.
 *
 * «Команди» на iPhone читають Apple Health і надсилають числа сюди. Ліплять
 * ту команду руками, з десятка однакових на вигляд дій, тож помилитись у
 * ній легко — а наслідок помилки не видно: запис або лягає не в ту колонку,
 * або тихо зникає, і людина дізнається про це через місяць, коли графік
 * виявляється порожнім.
 *
 * Тому розбір стоїть окремо від запису: те, що вирішує долю кожного числа,
 * має бути перевірене тестами, а не лише очима.
 */

/** Що взагалі приймаємо з годинника */
export const FROM_WATCH = [
  'steps', 'burned', 'water', 'workout', 'sleep', 'weight',
  'pulse', 'hrv', 'distance', 'stand', 'restEnergy', 'bodyFat',
];

/**
 * Діапазони, за межами яких число може бути лише помилкою заповнення.
 * Взяті з великим запасом: мета не «перевірити здоров'я», а зловити
 * підставлену не ту змінну — коли в вагу прилітають одинадцять тисяч кроків.
 */
export const SANE = {
  weight: [20, 400],        // кг
  bodyFat: [3, 70],         // %
  pulse: [25, 250],         // уд/хв
  hrv: [1, 500],            // мс
  sleep: [0, 24],           // год
  stand: [0, 24],           // год
  workout: [0, 1440],       // хв за добу
  water: [0, 20000],        // мл
  steps: [0, 200000],
  burned: [0, 20000],       // ккал
  restEnergy: [0, 10000],   // ккал
  distance: [0, 500],       // км
};

/** Нуль тут фізично неможливий — це порожня дія в «Командах», а не замір */
const NO_ZERO = ['pulse', 'hrv', 'weight', 'bodyFat'];

/**
 * Порожнє значення — це «не надсилали», а не нуль. Без цієї перевірки
 * Number('') дає 0, і поле, якого в запиті не було, затирало б збережене.
 */
export function num(v) {
  if (v === undefined || v === null) return null;
  // «Команди» можуть віддати число текстом і з роздільниками: «7 470»,
  // «7,470», «7 470,5». Прибираємо пробіли, а кому тлумачимо за контекстом:
  // разом із крапкою вона розділяє тисячі, сама по собі — дробову частину.
  let t = String(v).replace(/[\s  ]/g, '').trim();
  if (t === '') return null;
  if (t.includes(',') && t.includes('.')) t = t.replace(/,/g, '');
  else t = t.replace(',', '.');
  const n = Number(t);
  return Number.isFinite(n) ? n : null;
}

/**
 * Одиниці, у яких «Здоровʼя» розходиться з нашими колонками.
 *
 * Перетворюємо лише там, де переплутати неможливо: діапазони чужої й своєї
 * одиниці не перетинаються. Півпроцента жиру, тридцять мілілітрів води за
 * добу й двадцять п'ять годин стояння — не буває.
 */
export function fixUnits(raw) {
  const day = { ...raw };

  // частка → відсотки
  if (day.bodyFat > 0 && day.bodyFat <= 1) day.bodyFat = Math.round(day.bodyFat * 1000) / 10;

  // літри → мілілітри
  if (day.water > 0 && day.water < 50) day.water = Math.round(day.water * 1000);

  /*
   * Хвилини → години.
   *
   * Кільце стояння Apple віддає хвилини, а колонка чекає години — і в
   * добі рівно 24, тож усе, що більше, хвилинами й може бути лише воно.
   *
   * Раніше цього перетворення не було, і 480 хвилин стояння просто
   * відсіювались за межею: «Розминка» лишалась порожньою день за днем, а
   * відповідь команди про це мовчала — люди її не читають. Застосунок
   * натомість просив ділити на 60 у самій «Команді»: зайвий крок у
   * налаштуванні, який достатньо один раз пропустити.
   */
  if (day.stand > 24) day.stand = Math.round((day.stand / 60) * 10) / 10;

  return day;
}

/**
 * Викидає числа, які не могли прийти звідти, звідки прийшли.
 *
 * У «Командах» результат кожної дії зветься однаково, тож переплутати
 * змінні легко — і тоді кроки летять у вагу. Такий запис перекриває
 * справжній, і повертати доводиться руками через історію Google Таблиць.
 * Дешевше не пустити його всередину.
 */
export function dropInsane(raw) {
  const day = { ...raw };
  const ignored = [];
  Object.entries(SANE).forEach(([k, [lo, hi]]) => {
    if (day[k] === undefined) return;
    if (day[k] < lo || day[k] > hi) {
      ignored.push(`${k}=${day[k]} (чекали ${lo}–${hi})`);
      delete day[k];
    }
  });
  return { day, ignored };
}

/**
 * Тіло запиту від «Команд» → день, готовий до запису.
 *
 * Повертає й перелік викинутого: відповідь команди видно на телефоні
 * одразу, і саме там людина може побачити, що саме не долетіло.
 */
export function dayFromBody(body = {}, today = '') {
  const day = { date: String(body?.date || '').trim() || today };

  // беремо лише те, що справді надіслали: нуль теж значення, а порожнє — ні
  FROM_WATCH.forEach((k) => {
    const v = num(body?.[k]);
    if (v !== null) day[k] = v;
  });

  // Для кроків чи води нуль, навпаки, чесний: не ходив, не пив.
  NO_ZERO.forEach((k) => {
    if (day[k] === 0) delete day[k];
  });

  return dropInsane(fixUnits(day));
}

/** Чи лишилось у дні хоч одне число, крім самої дати */
export const hasNumbers = (day) => Object.keys(day || {}).length > 1;
