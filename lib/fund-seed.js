/**
 * Початковий стан фонду.
 *
 * Єдине місце, де числа написані руками. Усе решта виводиться
 * програванням книги, тому ці шість рядків і дві величини — весь ручний
 * ввід, який існує в розділі.
 *
 * Записуються вони **один раз**, кнопкою в застосунку: доступу до
 * таблиці з-поза застосунку немає ні в кого, хто пише цей код.
 */

import { kop } from './fund.js';

/** День, з якого ведеться облік. Періоди членства починаються з нього. */
export const OPENING_DATE = '2000-01-01';

/**
 * Шестеро з балансами на момент старту.
 *
 * `order` — стаж. Саме він вирішує, кому дістанеться зайва копійка, коли
 * платник не бере участі в витраті. Тримаємо його окремим полем, а не
 * порядком рядків: інакше перше ж сортування таблиці тихо змінить
 * відповідь.
 */
export const OPENING_MEMBERS = [
  { id: 'vanya', name: 'Ваня', order: 1, opening: kop('-4240') },
  { id: 'fantomas', name: 'Фантомас', order: 2, opening: kop('-3291') },
  { id: 'denis', name: 'Денис', order: 3, opening: kop('-2920') },
  { id: 'walter', name: 'Вальтер', order: 4, opening: kop('-2186') },
  { id: 'petya', name: 'Петя', order: 5, opening: kop('11514') },
  { id: 'fess', name: 'Фесс', order: 6, opening: kop('14320') },
].map((m) => ({
  ...m,
  // Денис вийшов із групи 20.10: кінець періоду виключний, тож 20.10 і далі
  // витрати на нього не ділимо, а його баланс лишається борговим
  periods: [m.id === 'denis' ? { start: OPENING_DATE, end: '2026-10-20' } : { start: OPENING_DATE }],
  vacations: [],
}));

/** Фізична готівка на старті */
export const OPENING_CASH = kop('13199');

/**
 * Готівки на 2,00 грн більше за суму балансів.
 *
 * Ці дві гривні **нікому не приписуємо** і заради краси жодного балансу
 * не правимо: розбіжність лишається видимою на екрані, доки не
 * з'ясується, звідки вона взялася.
 */
export const OPENING_DIFF = OPENING_CASH - OPENING_MEMBERS.reduce((a, m) => a + m.opening, 0);

/** Пари ключ-значення для листа налаштувань */
export const openingConfigRows = () => [
  ['openingCash', (OPENING_CASH / 100).toFixed(2)],
  ['openingDiff', (OPENING_DIFF / 100).toFixed(2)],
  ['openingDate', OPENING_DATE],
];
