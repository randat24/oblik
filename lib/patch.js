// Розширення тут стоїть навмисно, як і в сусідніх модулях: файл покритий
// тестами, а вбудований у Node запускач шукає його рівно за тим шляхом,
// який написали.

/**
 * Надсилати тільки те, що змінилось.
 *
 * Прогрес уроків, абетки й множення лежить у листі, який переписується
 * цілком. Доти, доки браузер надсилає весь свій стан, це означає тиху
 * втрату: відкрив сторінку на телефоні вранці, увечері відмітив щось на
 * компʼютері, потім телефон зберіг — і вечірні відмітки зникли, бо
 * телефон нічого про них не знав.
 *
 * Лікується з двох боків одразу, і жоден бік окремо не працює:
 *
 *   тут       — браузер лишає в посилці лише змінені записи;
 *   на сервері — прислане накладається на те, що вже в листі.
 *
 * Надішли браузер увесь стан — накладання нічого не врятує: застарілі
 * значення просто перекриють свіжі.
 *
 * Це не робить запис атомарним: два запити в ту саму секунду однаково
 * можуть накластись один на одного. Але вікно втрати стискається з годин
 * до мілісекунд, а для розділу, яким користується одна людина, цього
 * досить.
 */

/** Порівнюємо за вмістом: однакові значення дають однаковий рядок */
const same = (a, b) => JSON.stringify(a ?? null) === JSON.stringify(b ?? null);

/**
 * Що змінилось між тим, що прийшло з сервера, і тим, що стало.
 *
 * Записи, яких у новому стані немає, не потрапляють у результат: тутешні
 * листи нічого не видаляють, а лише додають і правлять. Зникле означало б
 * «я про нього не знаю», а не «його треба стерти».
 */
export function changedOnly(was, next) {
  const a = was || {};
  const b = next || {};
  const out = {};
  Object.keys(b).forEach((k) => {
    if (!same(a[k], b[k])) out[k] = b[k];
  });
  return out;
}

/** Накласти прислане на те, що вже є */
export function mergeMarks(current, patch) {
  return { ...(current || {}), ...(patch || {}) };
}

/** Чи є взагалі що записувати */
export const isEmptyPatch = (patch) => Object.keys(patch || {}).length === 0;
