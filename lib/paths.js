/*
 * Обовʼязкові теми, яких застосунок ще не вчить.
 *
 * Перелік навмисно окремий і перевіряється тестом: поки він тут, борг
 * названий. Зʼявиться ще одна обовʼязкова тема без шляху — тест упаде й
 * змусить або написати урок, або чесно дописати її сюди.
 *
 * Зараз він порожній: «Термінал» був тут останнім і закритий уроками про
 * інструменти. Решта пробілів — не обовʼязкові теми, і вони лишились
 * видимими в `gaps()`.
 */
export const MUST_GAPS = [];

/** Шлях до теми; для теми без шляху — порожній опис, а не `undefined` */
export const pathOf = (id) => PATHS[id] || {};

/** Чи є куди піти від теми всередині застосунку */
export function hasWhere(id) {
  const p = pathOf(id);
  return !!(p.lessons?.length || p.tools?.length || p.ref?.length
    || p.tour?.length || p.plan);
}

/**
 * Теми, які застосунок називає, але ніде не вчить.
 *
 * Це не помилка даних, а перелік роботи: саме ці теми й мають стати
 * наступними уроками. Показувати їх чесніше, ніж мовчати.
 */
export const gaps = () => Object.keys(PATHS).filter((id) => !hasWhere(id));

/** Скільки тем мають шлях — щоб було видно, наскільки карта заповнена */
export function coverage() {
  const all = Object.keys(PATHS);
  const covered = all.filter(hasWhere);
  return { covered: covered.length, total: all.length, gaps: all.length - covered.length };
}
