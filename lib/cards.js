// вбудований у Node запускач шукає модуль рівно за тим шляхом, який написали.

/**
 * Що показує шапка картки речі.
 *
 * Тут лише правила — жодного React і жодного читання таблиць, — бо саме
 * в цих правилах і сталася помилка, яку вони тепер стережуть: облік,
 * тип і місце винесли з тіла картки в короткі чипи, а чипи зробили
 * написами. Значення, що потрапило в чип, стало неможливо виправити; те,
 * що чип сховав як дубль статусу, зникло з екрана зовсім.
 */

/** Колонка «Оф облік»: числиться річ за документами чи ні */
export function accountingCol(headers) {
  return (headers || []).findIndex((h) => {
    const s = (h || '').toString().toLowerCase();
    return s.includes('облік') && !s.includes('не облік');
  });
}

/**
 * Короткі теги під назвою замість окремих рядків.
 *
 * Повертає два переліки, і другий тут не менш важливий за перший.
 *
 * `shown` — теги, які малюємо. Порожнє значення теж тег: інакше тип,
 * якого ще не вписали, не можна вписати взагалі — рядка в тілі картки
 * для нього вже немає, а чипа ще немає.
 *
 * `hidden` — колонки, тег яких ми вирішили не показувати, бо значення
 * повторює статус: «Де: КСП» поруч зі статусом «КСП» нічого не додає.
 * Такі колонки мусять лишитись у тілі картки звичайним рядком. Доки
 * вони звідти теж викидались, значення зникало з екрана зовсім — і
 * подивитись на нього було ніде, і виправити ніде.
 */
export function headTags(values, cols, accIdx) {
  const shown = [];
  const hidden = [];
  const status = (values[cols.status] || '').toString().trim().toLowerCase();
  const seen = new Set([status]);

  const add = (ci, cls) => {
    if (!(ci >= 0)) return;
    const v = (values[ci] || '').toString().trim();
    const key = v.toLowerCase();
    // значення, що дублює статус або інший тег, ховаємо — але не губимо
    if (v && seen.has(key)) { hidden.push(ci); return; }
    if (v) seen.add(key);
    shown.push({ ci, v, cls });
  };

  add(accIdx, 'tag-acc');
  add(cols.type, 'tag-type');
  add(cols.where > 0 ? cols.where : -1, 'tag-where');
  return { shown, hidden };
}

